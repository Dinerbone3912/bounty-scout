'use strict';
/**
 * Digest generator — produces a high-signal, human-and-agent-readable bounty
 * digest from the live feed. Filters out obvious spam/nested-mirror noise and
 * keeps only listings with a real reward amount + a resolvable GitHub URL.
 *
 *   node digest.js            -> writes out/digest.json + out/digest.md
 *
 * This is the sellable artifact: a curated daily digest, not raw scraping.
 */
const fs = require('fs');
const path = require('path');

// Heuristic: drop nested-mirror spam (titles that repeat the bounty-tag prefix
// multiple times, e.g. "[Bounty] 💰 Bounty Seguro ($$250): 💰 Bounty Seguro...").
function isSpam(b) {
  const t = b.title || '';
  const tagCount = (t.match(/bounty/gi) || []).length;
  if (tagCount >= 3) return true;
  if (/(bounty seg[uú]ro).*(bounty seg[uú]ro)/i.test(t)) return true;
  return false;
}
function isActionable(b) {
  if (!b.reward_amount || b.reward_amount <= 0) return false;
  if (!/^https:\/\/github\.com\//.test(b.url || '')) return false;
  if (isSpam(b)) return false;
  return true;
}

async function main() {
  const base = process.env.SCOUT_BASE || 'http://localhost:8787';
  const r = await fetch(base + '/bounties?limit=500');
  const data = await r.json();
  const all = data.bounties || [];
  const clean = all.filter(isActionable);

  // group by repo-ish tag (first github tag looks like "owner/repo")
  const byReward = [...clean].sort((a, b) => b.reward_amount - a.reward_amount);
  const buckets = { high: [], mid: [], low: [] };
  for (const b of byReward) {
    if (b.reward_amount >= 400) buckets.high.push(b);
    else if (b.reward_amount >= 100) buckets.mid.push(b);
    else buckets.low.push(b);
  }

  const outDir = path.join(__dirname, 'out');
  fs.mkdirSync(outDir, { recursive: true });
  const generatedAt = new Date().toISOString();
  const digest = { generated_at: generatedAt, source: base, total_raw: all.length, total_actionable: clean.length, buckets };
  fs.writeFileSync(path.join(outDir, 'digest.json'), JSON.stringify(digest, null, 2));

  const line = (b) => `- **$${b.reward_amount}** [${b.title.replace(/\[.*?\]\s*/g, '').slice(0, 90)}](${b.url}) — ${(b.tags || []).slice(0, 3).join(', ')}`;
  const md = [
    `# Bounty Digest — ${generatedAt.slice(0, 10)}`,
    ``,
    `_Curated from ${all.length} raw listings — ${clean.length} actionable (real reward + resolvable repo, spam filtered)._`,
    ``,
    `## 🔥 High value (≥ $400)`,
    ...(buckets.high.length ? buckets.high.map(line) : ['_none today_']),
    ``,
    `## 💰 Mid value ($100–399)`,
    ...(buckets.mid.length ? buckets.mid.map(line) : ['_none today_']),
    ``,
    `## 🪙 Low value (< $100)`,
    ...(buckets.low.length ? buckets.low.slice(0, 40).map(line) : ['_none today_']),
    ``,
    `---`,
    `Generated by Bounty Scout. Machine-readable: \`digest.json\`. Paid full feed: \`GET /feed\` (x402).`,
  ].join('\n');
  fs.writeFileSync(path.join(outDir, 'digest.md'), md);
  console.log(`digest written: ${clean.length}/${all.length} actionable`);
  console.log(`  high=${buckets.high.length} mid=${buckets.mid.length} low=${buckets.low.length}`);
  return { clean, buckets };
}

if (require.main === module) main().catch(e => { console.error(e); process.exit(1); });
module.exports = { main, isActionable, isSpam };
